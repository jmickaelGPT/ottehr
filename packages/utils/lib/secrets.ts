export type SecretsKey = (typeof SecretsKeys)[keyof typeof SecretsKeys];

export const getOptionalSecret = (key: SecretsKey | string, secrets: Secrets | null): string | undefined => {
  return secrets?.[key];
};

export const getSecret = (key: SecretsKey | string, secrets: Secrets | null): string => {
  const secret = getOptionalSecret(key, secrets);
  if (!secret) {
    throw new Error(`missing secret: ${String(key)}`);
  }
  return secret;
};
